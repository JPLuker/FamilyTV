import AxeBuilder from '@axe-core/playwright'
import {test,expect} from '@playwright/test'

test('parent can edit, export and remove a returning child profile',async({page,browser})=>{
  const password='temporary browser test password'
  async function checkAccessibility(target:typeof page){
    const {violations}=await new AxeBuilder({page:target}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
    expect(violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([])
  }
  await page.goto('/')
  await page.getByRole('heading',{name:'Create parent account'}).waitFor()
  await checkAccessibility(page)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button',{name:'Create account'}).click()
  await page.getByRole('heading',{name:'Parent sign in'}).waitFor()
  async function signIn(){
    await page.getByLabel('Password').fill(password)
    await page.getByRole('button',{name:'Sign in'}).click()
  }
  await signIn()
  await page.getByLabel('Profile name').fill('Robin')
  await page.getByLabel('Reduced motion').check()
  await page.getByLabel('High contrast').check()
  await page.getByLabel('Larger text').check()
  await page.getByLabel('Navigation').selectOption('visual-text')
  await page.getByRole('button',{name:'Add profile'}).click()
  await expect(page.getByRole('status')).toHaveText('Saved Robin.')
  await page.getByRole('button',{name:'Sign out'}).click()
  await signIn()
  await page.getByRole('button',{name:'Edit Robin'}).click()
  await expect(page.getByLabel('Reduced motion')).toBeChecked()
  await expect(page.getByLabel('Navigation')).toHaveValue('visual-text')
  await page.getByLabel('Captions').check()
  await page.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByRole('listitem')).toContainText('Captions')
  const exported=await page.request.get('/api/profiles/export')
  expect(exported.headers()['content-disposition']).toContain('attachment')
  const payload=await exported.json()
  expect(Object.keys(payload).sort()).toEqual(['profiles','version'])
  expect(payload.profiles[0]).toMatchObject({name:'Robin',captions:true,reduced_motion:true,navigation:'visual-text'})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.getByLabel('Video path in your media folder').fill('forest.webm')
  await page.getByRole('button',{name:'Import video'}).click()
  await page.getByRole('button',{name:'Review forest',exact:true}).click()
  await page.getByLabel('Subject').fill('Forests')
  await page.getByLabel('Caption quality').selectOption('verified')
  await page.getByLabel('Robin',{exact:true}).check()
  await page.getByRole('button',{name:'Save review'}).click()
  await expect(page.getByLabel('Library health')).toContainText('0 awaiting approval')
  await page.getByRole('button',{name:'Preview forest'}).click()
  const video=page.locator('video')
  await expect.poll(()=>video.evaluate(v=>v.readyState)).toBeGreaterThan(0)
  expect(await video.evaluate(v=>v.autoplay)).toBe(false)
  await page.getByText('Live TV channels',{exact:true}).click()
  await page.getByText('Import a Tunarr guide',{exact:true}).click()
  const xml='<tv><channel id="1"><display-name>Nature</display-name></channel><programme channel="1" start="20261123150000 -0500"><title>forest</title></programme></tv>'
  await page.getByLabel('XMLTV file').setInputFiles({name:'guide.xml',mimeType:'application/xml',buffer:Buffer.from(xml)})
  await page.getByRole('button',{name:'Use matching programs'}).click()
  await expect(page.getByLabel('Channel name')).toHaveValue('Nature')
  await page.getByRole('button',{name:'Create channel'}).click()
  await expect(page.getByRole('button',{name:'Remove channel Nature'})).toBeVisible()
  await page.getByRole('button',{name:'Viewing session for Robin'}).click()
  await page.getByLabel('Session ends').selectOption('one_video')
  await page.getByRole('button',{name:'Start session'}).click()
  const link=await page.getByLabel('One-time viewer link',{exact:false}).inputValue()
  const childContext=await browser.newContext()
  const child=await childContext.newPage()
  await child.goto(link)
  await expect(child.getByRole('button',{name:'Nature',exact:true})).toBeVisible()
  await checkAccessibility(child)
  await expect(child.locator('main')).toHaveClass(/contrast/)
  await expect(child.locator('main')).toHaveClass(/large/)
  const picture=child.getByRole('button',{name:'forest',exact:true}).locator('img')
  await expect.poll(()=>picture.evaluate(img=>img.naturalWidth)).toBeGreaterThan(0)
  await child.getByRole('button',{name:'forest',exact:true}).click()
  await expect(child.locator('video')).toBeVisible()
  await expect.poll(()=>child.locator('video').evaluate(v=>v.readyState)).toBeGreaterThan(0)
  expect(await child.locator('video').evaluate(v=>v.autoplay)).toBe(false)
  await child.getByRole('button',{name:'Finish video'}).click()
  await expect(child.getByRole('heading',{name:'Viewing time is over'})).toBeVisible()
  expect((await child.request.get('/api/profiles')).status()).toBe(401)
  await checkAccessibility(child)
  await childContext.close()
  await checkAccessibility(page)
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Remove video forest'}).click()
  await expect(video).toHaveCount(0)
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Remove Robin'}).click()
  await expect(page.getByRole('button',{name:'Remove Robin'})).toHaveCount(0)
  await page.getByRole('button',{name:'Sign out'}).click()
  await expect(page.getByRole('heading',{name:'Parent sign in'})).toBeVisible()
  expect((await page.request.get('/api/profiles/export')).status()).toBe(401)
})
